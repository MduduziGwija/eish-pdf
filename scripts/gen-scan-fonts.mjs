// Builds src/scan/fontlist.ts (the fonts used to redraw scanned text) and
// public/font-licenses.txt from the installed @fontsource packages.
// Run after adding or removing a font package:  node scripts/gen-scan-fonts.mjs
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const base = join(root, "node_modules", "@fontsource");
const KIND = { serif: "serif", "sans-serif": "sans", monospace: "mono", handwriting: "hand", display: "display" };
// Fonts bundled in the first place (the original set); the rest follow alphabetically.
const MAX_BYTES = Number(process.env.FONT_BUDGET ?? 60e6);

const rows = [];
let bytes = 0;
const wanted = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).dependencies;
for (const dep of Object.keys(wanted).filter((d) => d.startsWith("@fontsource/")).sort()) {
  const id = dep.slice("@fontsource/".length);
  const dir = join(base, id);
  if (!existsSync(join(dir, "metadata.json"))) continue;
  const meta = JSON.parse(readFileSync(join(dir, "metadata.json"), "utf8"));
  const kind = KIND[meta.category];
  if (!kind || !meta.subsets.includes("latin")) continue;
  const have = new Set(readdirSync(join(dir, "files")));
  const file = (w, s) => `${id}-latin-${w}-${s}.woff2`;
  if (!have.has(file(400, "normal"))) continue;
  const styles = [["400", "normal"], ["400", "italic"], ["700", "normal"], ["700", "italic"]].filter(([w, s]) => have.has(file(w, s)));
  const size = styles.reduce((n, [w, s]) => n + statSync(join(dir, "files", file(w, s))).size, 0);
  if (bytes + size > MAX_BYTES) continue;
  bytes += size;
  rows.push({ id, label: meta.family, kind, styles: styles.map(([w, s]) => `${w}-${s}`), license: meta.license?.type ?? "?", attribution: meta.license?.attribution ?? "" });
}

const ids = rows.map((r) => r.id);
const out = `// Generated by scripts/gen-scan-fonts.mjs: don't edit by hand.
export type Kind = "serif" | "sans" | "mono" | "hand" | "display";

export interface FontRow {
  id: string;
  label: string;
  kind: Kind;
  /** Which of regular, italic, bold and bold italic exist ("400-normal", "400-italic", "700-normal", "700-italic"). */
  styles: string[];
}

export const FONT_ROWS: FontRow[] = ${JSON.stringify(rows.map(({ id, label, kind, styles }) => ({ id, label, kind, styles })), null, 0).replace(/\},\{/g, "},\n  {")};

export const FONT_URLS = import.meta.glob("/node_modules/@fontsource/{${ids.join(",")}}/files/*-latin-{400,700}-{normal,italic}.woff2", { query: "?url", import: "default", eager: true }) as Record<string, string>;
`;
writeFileSync(join(root, "src", "scan", "fontlist.ts"), out);

const licences = rows.map((r) => `${r.label} (${r.license})${r.attribution ? ": " + r.attribution : ""}`).join("\n");
writeFileSync(join(root, "public", "font-licenses.txt"), `Fonts used by Eish PDF to redraw scanned text, from the Fontsource project (https://fontsource.org).\nEach font is free software under the licence named; see the links for the full texts.\n\n${licences}\n`);
console.log(`${rows.length} font families, ${(bytes / 1e6).toFixed(1)} MB`, Object.entries(rows.reduce((a, r) => ((a[r.kind] = (a[r.kind] ?? 0) + 1), a), {})));
